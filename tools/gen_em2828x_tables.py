import struct,sys
d=open(sys.argv[1],'rb').read()
pe=struct.unpack_from('<I',d,0x3c)[0]
nsec=struct.unpack_from('<H',d,pe+6)[0]; opt=struct.unpack_from('<H',d,pe+20)[0]
base=struct.unpack_from('<Q',d,pe+24+24)[0]
secs=[]
for i in range(nsec):
    o=pe+24+opt+i*40
    secs.append((struct.unpack_from('<I',d,o+12)[0],struct.unpack_from('<I',d,o+8)[0],struct.unpack_from('<I',d,o+20)[0],struct.unpack_from('<I',d,o+16)[0]))
def rd(addr,n):
    rva=addr-base
    for va,vs,ra,rs in secs:
        if va<=rva<va+max(vs,rs): return d[ra+rva-va:ra+rva-va+n]
    return None
out=[]
for idx in range(0,0x14):
    p=rd(0x1400b45c0+idx*16,8)
    if not p: break
    ptr=struct.unpack('<Q',p)[0]; cnt=struct.unpack('<H',rd(0x1400b45c8+idx*16,2))[0]
    raw=rd(ptr,cnt*2)
    if raw is None or cnt==0 or cnt>2000: print('stop',idx,hex(ptr),cnt,file=sys.stderr); break
    sh=struct.unpack('<%dH'%cnt,raw)
    stride=sh[-1]
    # validate: walk rows to terminator
    pos=0; ok=True
    while pos<cnt-1 and sh[pos]!=5:
        if sh[pos]>5: ok=False;break
        pos+=stride
    print(idx,hex(ptr),cnt,'stride',stride,'ok',ok,'end',pos,file=sys.stderr)
    out.append((idx,sh,stride))
print('/* Decoder register tables from embda64.sys (0x1400b45c0), generated by gentab.py.')
print(' * Rows of `stride` 16-bit words: op, register/mask, one value per column.')
print(' * op 0 = write column value, 1 = read-modify-write register, 2 = write register,')
print(' * 3 = skip next field if column is 0, 4 = field (mask, value), 5 = end. */')
for idx,sh,stride in out:
    rows=[]
    for i in range(0,len(sh),8):
        rows.append('    '+', '.join('0x%04x'%x for x in sh[i:i+8])+',')
    print('static const uint16_t dec_tbl_%02x[] = {\n%s\n};'%(idx,'\n'.join(rows)))
print('static const struct { const uint16_t *t; int n; } dec_tables[] = {')
for idx,sh,stride in out:
    print('    { dec_tbl_%02x, %d },'%(idx,len(sh)))
print('};')
